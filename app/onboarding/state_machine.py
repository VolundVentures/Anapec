class ReviewState(BaseState):
    name = "REVIEW"

    async def enter(self, user, db, wa, phone):
        summary = self._build_summary(user)
        await respond(wa, phone, user,
            "Show the user a summary of ALL their collected profile data and ask them to confirm "
            "everything is correct. If they want to change something, they can say what. "
            "If everything is good, they say 'ok'.",
            data={"profile_summary": summary})

    async def process(self, message_text, media_urls, media_types, user, db, wa, phone, ob_state):
        intent = await _classify_intent(message_text, {
            "confirm": "User confirms all profile data is correct, ready to finish",
            "edit": "User wants to change or fix something in their profile",
        }, context="Bot showed a complete profile summary and asked the user to confirm everything is correct")

        if intent == "confirm":
            return "COMPLETE"

        # Parse what they want to edit
        try:
            response = await gemini_chat(
                system="Identify what profile field the user wants to change. Return ONLY valid JSON: "
                       '{"field":"education|experience|languages|driving_license|extracurricular|cin|address|photo|name|other",'
                       '"details":"what they want"}',
                messages=[{"role": "user", "content": message_text}],
                max_tokens=256, temperature=0.1,
            )
            result = await _parse_json_response(response)
            edit_req = result if isinstance(result, dict) else {"field": "other"}
        except Exception:
            edit_req = {"field": "other"}

        field_state_map = {
            "education": "EDUCATION", "experience": "EXPERIENCE",
            "languages": "LANGUAGES", "driving_license": "DRIVING_LICENSE",
            "extracurricular": "EXTRACURRICULAR", "cin": "CIN_FRONT",
            "address": "CIN_BACK", "photo": "PHOTO", "name": "CIN_FRONT",
        }

        redirect_state = field_state_map.get(edit_req.get("field"))
        if redirect_state:
            await respond(wa, phone, user,
                f"The user wants to edit their {edit_req.get('field')}. "
                f"Confirm you'll redo that section and redirect them.")
            return redirect_state
        else:
            await respond(wa, phone, user,
                "Couldn't understand what they want to change. Ask them to be more specific: "
                "'change experience', 'add diploma', 'change name', etc.")
            return None

    def _build_summary(self, user: User) -> dict:
        """Build a structured summary of all collected data."""
        summary = {}
        if user.full_name_latin:
            summary["Nom"] = user.full_name_latin
        if user.cin_number:
            summary["CIN"] = user.cin_number
        if user.date_of_birth:
            summary["Date de naissance"] = user.date_of_birth
        if user.city:
            summary["Ville"] = user.city
        if user.address:
            summary["Adresse"] = user.address
        if user.gender:
            summary["Genre"] = "Homme" if user.gender == "M" else "Femme"

        edu = user.education or []
        if edu:
            summary["Formation"] = [
                f"{e.get('degree_name', '?')} - {e.get('institution', '?')} ({e.get('year', '?')})"
                for e in edu if isinstance(e, dict)
            ]

        exp = user.experience or []
        if exp:
            summary["Experience"] = [
                f"{x.get('title', '?')} @ {x.get('company', '?')} ({x.get('period', '?')})"
                for x in exp if isinstance(x, dict)
            ]

        langs = user.languages_spoken or []
        if langs:
            summary["Langues"] = [f"{l.get('language', '?')} ({l.get('level', '?')})" for l in langs if isinstance(l, dict)]

        if user.driving_license and user.driving_license != "none":
            summary["Permis"] = user.driving_license

        if user.extracurricular:
            summary["Activites"] = [a.get("activity", "?") for a in user.extracurricular if isinstance(a, dict)]

        if user.industry_category:
            summary["Domaine"] = user.industry_category

        summary["Photo"] = "Oui" if user.photo_b64 else "Non"
        summary["Completeness"] = f"{_calc_completeness(user)}%"

        return summary


