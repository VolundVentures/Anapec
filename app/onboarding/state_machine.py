class LanguagePrefState(BaseState):
    name = "LANGUAGE_PREF"

    async def enter(self, user, db, wa, phone):
        detected = user.language or "darija"
        lang_names = {"darija": "Darija", "fr": "Francais", "ar": "Arabe"}
        await respond(wa, phone, user,
            f"You detected the user speaks {lang_names.get(detected, 'Darija')}. "
            f"Ask them to confirm: 1. Darija  2. Francais  3. Arabe. "
            f"Keep it very short, just confirm the language.")

    async def process(self, message_text, media_urls, media_types, user, db, wa, phone, ob_state):
        lang = await _classify_intent(message_text, {
            "darija": "User chose Darija (option 1, or said darija/darja/الدارجة)",
            "fr": "User chose French (option 2, or said francais/français/french)",
            "ar": "User chose Arabic (option 3, or said arabe/arabic/عربية/العربية)",
        }, context="User is choosing their preferred language: 1. Darija  2. Français  3. Arabe")

        crud.update_user(db, user, language=lang)
        _update_completeness(db, user)
        return "COMM_PREF"


