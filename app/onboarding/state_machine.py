class CINFrontState(BaseState):
    name = "CIN_FRONT"

    async def enter(self, user, db, wa, phone):
        await respond(wa, phone, user,
            "Ask the user to send a photo of the FRONT of their CIN (national ID card). "
            "The front side has their name, CIN number, and date of birth. "
            "If they prefer, they can type 'skip' for manual entry.")

    async def process(self, message_text, media_urls, media_types, user, db, wa, phone, ob_state):
        step_data = dict(ob_state.step_data or {})

        # Awaiting confirmation of OCR results
        if step_data.get("awaiting_confirmation"):
            intent = await _classify_intent(message_text, {
                "confirm": "User confirms the extracted data is correct",
                "correct": "User wants to fix or change something in the data",
            }, context="Bot showed OCR-extracted CIN data (name, CIN number, date of birth) and asked if it's correct")

            if intent == "confirm":
                step_data.pop("awaiting_confirmation", None)
                crud.update_onboarding_state(db, ob_state, step_data=step_data)
                _update_completeness(db, user)
                return "CIN_BACK"

            # User wants corrections — parse what they want to change
            corrections = await _parse_correction(
                message_text,
                step_data.get("ocr_result", {}),
                ["full_name_latin", "full_name_arabic", "cin_number", "date_of_birth"],
            )
            if corrections:
                updates = {}
                for field, value in corrections.items():
                    if field == "full_name_latin":
                        updates["full_name_latin"] = value
                        updates["name"] = value
                    elif field == "full_name_arabic":
                        updates["full_name_arabic"] = value
                    elif field == "cin_number":
                        updates["cin_number"] = value
                    elif field == "date_of_birth":
                        updates["date_of_birth"] = value
                if updates:
                    crud.update_user(db, user, **updates)
                    _update_completeness(db, user)
                step_data.pop("awaiting_confirmation", None)
                crud.update_onboarding_state(db, ob_state, step_data=step_data)
                await respond(wa, phone, user,
                    "Confirm the corrections are saved. Say let's continue to the next step.")
                return "CIN_BACK"

            # Couldn't parse specific corrections — ask what to fix
            await respond(wa, phone, user,
                "Ask the user to specify exactly what needs to be corrected in the CIN data.")
            return None

        # Manual entry mode
        if step_data.get("manual_mode"):
            return await self._process_manual(message_text, user, db, wa, phone, ob_state, step_data)

        # Has media → OCR
        if media_urls:
            pass  # fall through to OCR below
        else:
            # No media — classify: skip or something else?
            intent = await _classify_intent(message_text, {
                "skip": "User wants to skip CIN photo and enter data manually",
                "other": "User is asking a question or saying something else",
            }, context="Bot asked for a photo of the front of their CIN (national ID card). User can skip for manual entry.")

            if intent == "skip":
                return await self._handle_manual(user, db, wa, phone, ob_state)

            attempts = ob_state.attempts + 1
            crud.update_onboarding_state(db, ob_state, attempts=attempts)
            if attempts >= MAX_IMAGE_ATTEMPTS:
                return await self._handle_manual(user, db, wa, phone, ob_state)
            await respond(wa, phone, user,
                f"Ask them to send a PHOTO of their CIN front. "
                f"Or they can say they want to skip. Attempt {attempts}/{MAX_IMAGE_ATTEMPTS}.")
            return None

        # Download and OCR
        try:
            image_data, content_type = await download_twilio_media(media_urls[0])
            result = await _ocr_image(image_data, content_type, "cin_front")

            if result and (result.get("cin_number") or result.get("full_name_latin")):
                updates = {}
                if result.get("cin_number"):
                    updates["cin_number"] = result["cin_number"]
                if result.get("full_name_latin"):
                    updates["full_name_latin"] = result["full_name_latin"]
                    updates["name"] = result["full_name_latin"]
                if result.get("full_name_arabic"):
                    updates["full_name_arabic"] = result["full_name_arabic"]
                if result.get("date_of_birth"):
                    updates["date_of_birth"] = result["date_of_birth"]

                cin_data = dict(user.cin_data or {})
                cin_data["front"] = result
                updates["cin_data"] = cin_data
                crud.update_user(db, user, **updates)
                _update_completeness(db, user)

                # Build data summary for the AI to present
                extracted = {}
                if result.get("full_name_latin"):
                    extracted["Nom"] = result["full_name_latin"]
                if result.get("cin_number"):
                    extracted["CIN"] = result["cin_number"]
                if result.get("date_of_birth"):
                    extracted["Date de naissance"] = result["date_of_birth"]
                if result.get("lieu_de_naissance"):
                    extracted["Lieu de naissance"] = result["lieu_de_naissance"]

                step_data["ocr_result"] = result
                step_data["awaiting_confirmation"] = True
                crud.update_onboarding_state(db, ob_state, step_data=step_data)

                await respond(wa, phone, user,
                    "Show the user the data below from their CIN. "
                    "Ask: is this correct? If something is wrong, tell me what to fix.",
                    data=extracted)
                return None
            else:
                attempts = ob_state.attempts + 1
                crud.update_onboarding_state(db, ob_state, attempts=attempts)
                if attempts >= MAX_IMAGE_ATTEMPTS:
                    return await self._handle_manual(user, db, wa, phone, ob_state)
                await respond(wa, phone, user,
                    f"The photo wasn't clear enough. Ask for a clearer photo of the CIN front. "
                    f"Attempt {attempts}/{MAX_IMAGE_ATTEMPTS}. Or say 'skip'.")
                return None

        except Exception as e:
            logger.error(f"CIN front processing error: {e}", exc_info=True)
            attempts = ob_state.attempts + 1
            crud.update_onboarding_state(db, ob_state, attempts=attempts)
            if attempts >= MAX_IMAGE_ATTEMPTS:
                return await self._handle_manual(user, db, wa, phone, ob_state)
            await respond(wa, phone, user,
                "There was a problem processing the image. Ask the user to resend or say 'skip'.")
            return None

    async def _handle_manual(self, user, db, wa, phone, ob_state):
        step_data = dict(ob_state.step_data or {})
        step_data["manual_mode"] = True
        step_data["manual_step"] = "full_name"
        crud.update_onboarding_state(db, ob_state, step_data=step_data)
        await respond(wa, phone, user,
            "We'll enter the CIN info manually. Ask for their full name (in French or Arabic).")
        return None

    async def _process_manual(self, message_text, user, db, wa, phone, ob_state, step_data):
        text_val = message_text.strip()
        manual_step = step_data.get("manual_step", "full_name")

        if manual_step == "full_name":
            crud.update_user(db, user, full_name_latin=text_val, name=text_val)
            step_data["manual_step"] = "cin_number"
            crud.update_onboarding_state(db, ob_state, step_data=step_data)
            await respond(wa, phone, user,
                "Name saved. Now ask for their CIN number (format: 1-2 letters + digits, e.g., AB123456).")
            return None

        elif manual_step == "cin_number":
            crud.update_user(db, user, cin_number=text_val)
            step_data["manual_step"] = "date_of_birth"
            crud.update_onboarding_state(db, ob_state, step_data=step_data)
            await respond(wa, phone, user,
                "CIN number saved. Now ask for their date of birth (format: DD/MM/YYYY, e.g., 15/03/1995).")
            return None

        elif manual_step == "date_of_birth":
            crud.update_user(db, user, date_of_birth=text_val)
            _update_completeness(db, user)
            return "CIN_BACK"

        return None


