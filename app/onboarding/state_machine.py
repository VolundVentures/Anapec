class CommPrefState(BaseState):
    name = "COMM_PREF"

    async def enter(self, user, db, wa, phone):
        crud.update_user(db, user, communication_pref="voice")
        _update_completeness(db, user)
        await respond(wa, phone, user,
            "Confirm to the user that you'll respond with voice messages from now on. "
            "Tell them they can switch to text anytime by saying 'text'. "
            "Then tell them: now let's build your profile, starting with the CIN (national ID card). "
            "Ask them to send a photo of the FRONT of their CIN (the side with their name and number). "
            "If they don't want to, they can say 'skip' for manual entry.")

    async def process(self, message_text, media_urls, media_types, user, db, wa, phone, ob_state):
        if media_urls:
            # User already sent a CIN photo — transition to CIN_FRONT and process it there
            crud.set_onboarding_step(db, user.id, "CIN_FRONT")
            crud.update_user(db, user, onboarding_step="CIN_FRONT")
            new_ob = crud.get_onboarding_state(db, user.id)
            cin_front = CINFrontState()
            result = await cin_front.process(message_text, media_urls, media_types, user, db, wa, phone, new_ob)
            return result  # None (awaiting confirm) or "CIN_BACK"
        return "CIN_FRONT"


