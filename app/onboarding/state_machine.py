async def respond(wa, phone: str, user, task: str, data: dict = None) -> None:
    """Generate a WhatsApp message via Gemini and send through dispatcher."""
    lang = getattr(user, "language", "darija") or "darija"
    input_obj = {"task": task, "lang": lang}
    if data:
        input_obj["data"] = data
    prompt = json.dumps(input_obj, ensure_ascii=False)

    try:
        text = await gemini_chat(
            system=ONBOARDING_SYSTEM,
            messages=[{"role": "user", "content": prompt}],
            max_tokens=2048,
            temperature=0.7,
            thinking_budget=1024,
        )
        text = text.strip()
        if not text:
            text = task  # fallback
    except Exception as e:
        logger.error(f"Gemini respond failed: {e}", exc_info=True)
        logger.error(f"Gemini failed: {e}")
        text = task

    await send_response(phone, text, user, wa)


async def respond_raw(wa, phone: str, user, text: str) -> None:
    """Send a pre-built message through the dispatcher (voice/text)."""
    await send_response(phone, text, user, wa)


def _calc_completeness(user: User) -> int:
    """Calculate profile completeness as a percentage (0-100)."""
    score = 0
    total = 0

    total += 15
    if user.cin_number:
        score += 8
    if user.full_name_latin or user.full_name_arabic:
        score += 4
    if user.date_of_birth:
        score += 3

    total += 5
    if user.address:
        score += 3
    if user.gender:
        score += 2

    total += 20
    edu = user.education or []
    if edu:
        score += min(20, len(edu) * 10)

    total += 25
    exp = user.experience or []
    if exp:
        score += min(25, len(exp) * 8)

    total += 5
    if user.languages_spoken:
        score += 5

    total += 3
    if user.driving_license:
        score += 3

    total += 5
    if user.extracurricular:
        score += 5

    total += 7
    if user.photo_b64:
        score += 7

    total += 10
    if user.industry_category:
        score += 5
    if user.industry_details:
        score += 5

    total += 2
    if user.communication_pref:
        score += 2

    total += 3
    if user.language:
        score += 3

    return int((score / total) * 100) if total > 0 else 0


def _update_completeness(db, user: User):
    pct = _calc_completeness(user)
    crud.update_user(db, user, profile_completeness=pct)


async def _ocr_image(image_data: bytes, media_type: str, extraction_type: str) -> dict | None:
    """Run OCR via Claude vision on an image."""
    from app.agent.claude_client import chat_with_image
    from app.agent.prompts import CIN_FRONT_EXTRACTION, CIN_BACK_EXTRACTION, DIPLOMA_EXTRACTION

    prompt_map = {
        "cin_front": CIN_FRONT_EXTRACTION,
        "cin_back": CIN_BACK_EXTRACTION,
        "diploma": DIPLOMA_EXTRACTION,
    }
    system_prompt = prompt_map.get(extraction_type, CIN_FRONT_EXTRACTION)

    try:
        response = await chat_with_image(
            system=system_prompt,
            messages=[],
            image_data=image_data,
            media_type=media_type,
            max_tokens=1024,
        )
        text = response.strip()
        if "```" in text:
            text = text.split("```")[1]
            if text.startswith("json"):
                text = text[4:]
            text = text.strip()
        return json.loads(text)
    except Exception as e:
        logger.error(f"OCR ({extraction_type}) failed: {e}", exc_info=True)
        return None


async def _parse_json_response(response_text: str) -> dict | list | None:
    """Clean and parse a JSON response from Gemini."""
    text = response_text.strip()
    if "```" in text:
        text = text.split("```")[1]
        if text.startswith("json"):
            text = text[4:]
        text = text.strip()
    try:
        return json.loads(text)
    except Exception:
        return None


async def _classify_intent(user_message: str, intents: dict[str, str], context: str = "") -> str:
    """Use Gemini to classify user intent from a natural language message.

    Args:
        user_message: The raw user message (any language/dialect)
        intents: Dict mapping intent_name → description
        context: What the bot just asked / what we're expecting

    Returns:
        One of the intent names (keys of intents dict)
    """
    intent_list = "\n".join(f"- {k}: {v}" for k, v in intents.items())
    fallback = list(intents.keys())[-1]

    prompt = (
        f'User message: "{user_message}"\n'
        f'Context: {context}\n\n'
        f"Classify into exactly ONE of these intents:\n{intent_list}\n\n"
        f"Return ONLY the intent name, nothing else."
    )

    try:
        response = await gemini_chat(
            system="You are an intent classifier for a Moroccan WhatsApp bot. "
                   "Users speak Darija (Latin script with numbers: 3=ع, 7=ح, 9=ق), French, or Arabic. "
                   "Return ONLY the intent label — one word, no quotes, no explanation.",
            messages=[{"role": "user", "content": prompt}],
            max_tokens=256,
            temperature=0.0,
        )
        result = response.strip().lower().strip('"\'.,!:')
        for intent_name in intents:
            if intent_name.lower() in result:
                return intent_name
        return fallback
    except Exception as e:
        logger.error(f"Intent classification failed: {e}")
        return fallback


async def _parse_correction(user_message: str, ocr_result: dict, valid_fields: list[str]) -> dict | None:
    """Use Gemini to understand partial corrections from the user."""
    fields_str = json.dumps(ocr_result, ensure_ascii=False)
    prompt = f"""The user was shown these OCR-extracted fields:
{fields_str}

The user replied: "{user_message}"

Extract ONLY the fields they want to change. Valid field names: {valid_fields}
If the user says everything is correct, return {{}}.
If you can't understand, return null.
Return ONLY valid JSON."""

    try:
        response = await gemini_chat(
            system="You parse user corrections for OCR data. Return only valid JSON.",
            messages=[{"role": "user", "content": prompt}],
            max_tokens=256,
            temperature=0.1,
        )
        result = await _parse_json_response(response)
        return result if isinstance(result, dict) else None
    except Exception as e:
        logger.error(f"Correction parsing failed: {e}", exc_info=True)
        return None


