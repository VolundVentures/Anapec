class BaseState(ABC):
    name: str = ""

    @abstractmethod
    async def enter(self, user: User, db, wa, phone: str):
        ...

    @abstractmethod
    async def process(self, message_text: str, media_urls: list[str], media_types: list[str],
                      user: User, db, wa, phone: str, ob_state: OnboardingStateModel) -> str | None:
        ...


# ─────────────────────────────────────────────
# 1. WELCOME
# ─────────────────────────────────────────────

class WelcomeState(BaseState):
    name = "WELCOME"

    async def enter(self, user, db, wa, phone):
        await respond(wa, phone, user,
            "Welcome the user to Anapec AI. Introduce yourself as their career assistant. "
            "Tell them you can help with: professional CV creation, job search, skills assessment (bilan des competences), "
            "and ANAPEC info. Ask them to say something so you can detect their language. "
            "Keep it warm and short. Write the welcome in BOTH Darija and French since we don't know their language yet.")

    async def process(self, message_text, media_urls, media_types, user, db, wa, phone, ob_state):
        detected = await _classify_intent(message_text, {
            "darija": "Moroccan Darija — Arabic dialect, often Latin script with numbers (3,7,9,5,8)",
            "fr": "French language",
            "ar": "Modern Standard Arabic in Arabic script",
        }, context="Detect the language of this first message from a Moroccan user")

        crud.update_user(db, user, language=detected)

        step_data = dict(ob_state.step_data or {})
        step_data["detected_language"] = detected
        step_data["first_message"] = message_text[:200]
        crud.update_onboarding_state(db, ob_state, step_data=step_data)

        return "LANGUAGE_PREF"


