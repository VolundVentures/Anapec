class ExperienceState(BaseState):
    name = "EXPERIENCE"

    async def enter(self, user, db, wa, phone):
        await respond(wa, phone, user,
            "Now let's talk about their professional experience. This is the MOST IMPORTANT part of their CV. "
            "Ask about their most recent job: title, company, duration, daily responsibilities, achievements. "
            "Be a coach — push for details. 'Worked in logistics' is not enough, we need specifics! "
            "If they have no experience, they can say so.")

    async def process(self, message_text, media_urls, media_types, user, db, wa, phone, ob_state):
        step_data = dict(ob_state.step_data or {})

        # Drilling deeper into current job (don't classify intent during drill)
        if step_data.get("current_job") and step_data.get("drilling"):
            return await self._drill_deeper(message_text, user, db, wa, phone, ob_state, step_data)

        # Classify intent
        intent = await _classify_intent(message_text, {
            "done": "User is done adding jobs, or has no professional experience at all",
            "content": "User is describing a job, work experience, or professional activity",
        }, context="Bot asked about professional experience. User can describe jobs or say they have none/are done.")

        if intent == "done":
            _update_completeness(db, user)
            if not step_data.get("has_at_least_one"):
                await respond(wa, phone, user,
                    "Acknowledge they have no experience. That's ok, we'll work with what they have. Moving on.")
            return "EXTRACURRICULAR"

        # Parse experience
        job = await self._parse_experience_text(message_text)

        missing = []
        if not job.get("title"):
            missing.append("job title")
        if not job.get("company"):
            missing.append("company name")
        if not job.get("period"):
            missing.append("time period")
        if not job.get("responsibilities") or len(str(job.get("responsibilities", ""))) < 20:
            missing.append("detailed daily responsibilities")

        if missing:
            step_data["current_job"] = job
            step_data["drilling"] = True
            crud.update_onboarding_state(db, ob_state, step_data=step_data)

            await respond(wa, phone, user,
                f"The user gave some job info but we still need: {', '.join(missing)}. "
                f"Push for more details like a career coach — the CV depends on it! "
                f"Already collected: {json.dumps(job, ensure_ascii=False)}",
                data={"collected": job, "missing": missing})
            return None

        return await self._save_job(job, user, db, wa, phone, ob_state, step_data)

    async def _drill_deeper(self, message_text, user, db, wa, phone, ob_state, step_data):
        current_job = step_data.get("current_job", {})
        merged = await self._merge_experience(current_job, message_text)

        missing = []
        if not merged.get("title"):
            missing.append("job title")
        if not merged.get("responsibilities") or len(str(merged.get("responsibilities", ""))) < 20:
            missing.append("detailed responsibilities")

        if missing and ob_state.attempts < 3:
            step_data["current_job"] = merged
            crud.update_onboarding_state(db, ob_state, step_data=step_data, attempts=ob_state.attempts + 1)
            await respond(wa, phone, user,
                f"Thanks for the info! But still need: {', '.join(missing)}. "
                f"Push gently for more specifics. This makes the CV stand out.",
                data={"collected": merged, "still_missing": missing})
            return None

        return await self._save_job(merged, user, db, wa, phone, ob_state, step_data)

    async def _save_job(self, job, user, db, wa, phone, ob_state, step_data):
        exp_list = list(user.experience or [])
        exp_list.append(job)
        crud.update_user(db, user, experience=exp_list)

        step_data["has_at_least_one"] = True
        step_data.pop("current_job", None)
        step_data.pop("drilling", None)
        crud.update_onboarding_state(db, ob_state, step_data=step_data, attempts=0)

        await respond(wa, phone, user,
            "Show the job info below. Ask if they have another job to add, or say 'done'.",
            data={"saved": job, "total_jobs": len(exp_list)})
        return None

    async def _parse_experience_text(self, text: str) -> dict:
        try:
            response = await gemini_chat(
                system="Extract job experience. Return ONLY valid JSON: "
                       '{"title":"","company":"","period":"","responsibilities":"","achievements":"","city":""}',
                messages=[{"role": "user", "content": text}],
                max_tokens=512, temperature=0.1,
            )
            result = await _parse_json_response(response)
            return result if isinstance(result, dict) else {"responsibilities": text.strip()[:300]}
        except Exception:
            return {"title": "", "company": "", "responsibilities": text.strip()[:300]}

    async def _merge_experience(self, existing: dict, new_text: str) -> dict:
        try:
            response = await gemini_chat(
                system="Merge partial job data with new info. Return ONLY valid JSON: "
                       '{"title":"","company":"","period":"","responsibilities":"","achievements":"","city":""}',
                messages=[{"role": "user",
                           "content": f"Existing: {json.dumps(existing, ensure_ascii=False)}\nNew info: {new_text}"}],
                max_tokens=512, temperature=0.1,
            )
            result = await _parse_json_response(response)
            if isinstance(result, dict):
                for k, v in existing.items():
                    if k not in result or not result[k]:
                        result[k] = v
                return result
        except Exception:
            pass
        existing["responsibilities"] = ((existing.get("responsibilities") or "") + " " + new_text).strip()
        return existing


